/** A listing as rendered in grids and cards. */
export type ListingSummary = {
  id: string;
  title: string;
  location: string;
  city: string;
  cityLabel: string;
  /**
   * The raw English country ("United Kingdom"). The `*Label` fields are the
   * authored Chinese labels kept for the API and the Agent; the UI renders the
   * country and city through `countryName` / `cityName` so a reader of the
   * English or Japanese UI does not get "英国" in the middle of an address.
   */
  country: string;
  countryLabel: string;
  pricePerNight: number;
  propertyType: PropertyTypeValue;
  propertyTypeLabel: string;
  rating: number;
  reviewCount: number;
  maxGuests: number;
  bedrooms: number;
  beds: number;
  bathrooms: number;
  /** Primary (hero) image. */
  image: string;
  images: string[];
  amenityNames: string[];
  hostName: string;
  latitude: number;
  longitude: number;
  /**
   * Localised title / address keyed by locale, generated by the seed. The Chinese
   * `title` / `location` remain the authored values the API and Agent read;
   * the UI prefers these when they exist.
   */
  titleI18n?: Record<string, string> | null;
  locationI18n?: Record<string, string> | null;
};

